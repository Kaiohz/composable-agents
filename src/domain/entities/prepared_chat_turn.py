"""Temporary RustFS document reference (chat PDF attachments spec §5.3/5.4).

Temporary chat documents live under the agent-scoped root prefix (user ×
agent directive, chat_tmp Option 2):

.. code-block:: text

    <user_id>/<agent_slug>/chat_tmp/<thread_id>/<attachment_id>/<filename>

The user × agent identity is composed SERVER-SIDE (mcp-raganything composes
the REQUIRED agent scope from the ``X-Composable-Agent`` header); the
backend-relative object path therefore carries NO user segment. The object
path is built and kept in memory by the backend during the turn; it is
derivable for HITL-resume cleanup from the HUMAN_MESSAGE trace metadata
(id + filename) using :func:`temporary_object_path` (REQ-043/REQ-044).
"""

from typing import Any

from pydantic import BaseModel, Field

TEMP_ROOT_PREFIX = "chat_tmp"


def is_safe_segment(value: str) -> bool:
    """Return True when ``value`` is a single safe path segment.

    A safe segment is non-empty, contains no separator, no traversal token and
    no control characters (NFR-008/NFR-009, REQ-039).

    Args:
        value: Candidate segment.

    Returns:
        True when the segment is safe to embed in an object path.
    """
    if not value or value != value.strip():
        return False
    if "/" in value or "\\" in value:
        return False
    if value in (".", ".."):
        return False
    return not any(ord(char) < 32 for char in value)


def temporary_object_path(thread_id: str, attachment_id: str, filename: str) -> str:
    """Build the RELATIVE temporary object path for a chat attachment.

    Args:
        thread_id: Conversation thread identifier.
        attachment_id: Unique per-attachment identifier (EDG-006).
        filename: Attachment basename.

    Returns:
        The ``chat_tmp/<thread_id>/<attachment_id>/<filename>`` RELATIVE path
        (the user × agent identity is composed server-side — chat_tmp
        Option 2).

    Raises:
        ValueError: When any segment is unsafe (path traversal guard, REQ-039).
    """
    for name, value in (
        ("thread_id", thread_id),
        ("attachment_id", attachment_id),
        ("filename", filename),
    ):
        if not is_safe_segment(value):
            raise ValueError(f"Unsafe temporary path segment for {name}")
    return f"{TEMP_ROOT_PREFIX}/{thread_id}/{attachment_id}/{filename}"


def temporary_prefix(thread_id: str, attachment_id: str) -> str:
    """Build the RELATIVE temporary prefix WITHOUT the filename segment.

    Args:
        thread_id: Conversation thread identifier.
        attachment_id: Unique per-attachment identifier.

    Returns:
        The ``chat_tmp/<thread_id>/<attachment_id>/`` prefix with a trailing
        slash.

    Raises:
        ValueError: When any segment is unsafe (path traversal guard, REQ-039).
    """
    for name, value in (("thread_id", thread_id), ("attachment_id", attachment_id)):
        if not is_safe_segment(value):
            raise ValueError(f"Unsafe temporary path segment for {name}")
    return f"{TEMP_ROOT_PREFIX}/{thread_id}/{attachment_id}/"


class TemporaryDocumentRef(BaseModel, frozen=True):
    """A temp RustFS object uploaded for the current turn, awaiting cleanup.

    Attributes:
        attachment_id: Unique identifier generated by the backend (EDG-006).
        filename: Attachment basename.
        object_path: Full ``chat_tmp/...`` object path managed by the backend.
    """

    attachment_id: str
    filename: str
    object_path: str

    @property
    def user_prefix(self) -> str:
        """Return the user-scoped root of the object path (``chat_tmp/<user_id>/``).

        Cleanup is restricted to the current user's prefix (REQ-047).
        """
        parts = self.object_path.split("/")
        return "/".join(parts[:2]) if len(parts) >= 2 else self.object_path


class PreparedChatTurn(BaseModel, frozen=True):
    """Attachments prepared for one chat turn, ready for the runner.

    Attributes:
        text: The original user text (may be ``None`` for attachments-only
            turns, REQ-004).
        content_blocks: Standard multimodal content blocks (REQ-012/REQ-018);
            ``None`` when the turn carries no attachments (legacy string path,
            REQ-017).
        attachments_metadata: Projection-safe attachment metadata entries for
            the HUMAN_MESSAGE trace event (REQ-020; no base64, REQ-021).
        temporary_documents: Temp RustFS refs to delete after the terminal
            response (REQ-041/REQ-042).
    """

    text: str | None = None
    content_blocks: list[dict[str, Any]] | None = None
    attachments_metadata: list[dict[str, Any]] = Field(default_factory=list)
    temporary_documents: list[TemporaryDocumentRef] = Field(default_factory=list)
    # The turn's agent, resolved by the preparation service so post-preparation
    # failures (runner build, graph error) can still clean up without a second
    # thread lookup (REQ-042 no-orphan guarantee, chat review C1).
    agent_name: str | None = None

    @property
    def has_attachments(self) -> bool:
        """Return True when the turn carries any prepared attachment."""
        return bool(self.content_blocks)
